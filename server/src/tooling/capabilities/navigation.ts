import type { Catalog } from './catalog-types';
import { fingerprint } from './source';

function cell(value: string, maximum: number): string {
  const text = value.replace(/\s+/g, ' ').trim();
  return (text.length > maximum ? `${text.slice(0, maximum - 1)}…` : text).replace(/[\\|`*_[\]<>]/g, '\\$&');
}

export function renderNavigationIndex(catalog: Catalog): string {
  const inventory = catalog.inventory;
  if (!inventory || catalog.status.state === 'invalid') throw new Error('A valid catalog is required to render navigation');
  const records = [...catalog.records].sort((a, b) => a.domain.localeCompare(b.domain, 'en') || a.id.localeCompare(b.id, 'en'));
  const domains = new Map<string, number>();
  for (const record of records) domains.set(record.domain, (domains.get(record.domain) ?? 0) + 1);
  const lines = [
    '# Repository capability navigation', '',
    'Generated by catalog refresh; agents maintain the explanation records, not this page.',
    'This is a snapshot. Run `check` before relying on it; fresh source evidence does not prove a feature works.', '',
    '[Agent reuse workflow](../../server/src/tooling/capabilities/README.md#agent-reuse-workflow)', '',
    'From `server/`:', '', '```sh',
    'npx ts-node src/bin/catalog-capabilities.ts check',
    'npx ts-node src/bin/catalog-capabilities.ts search "<task or setting>" --limit 6',
    'npx ts-node src/bin/catalog-capabilities.ts get <ID>', '```', '',
    `${inventory.files.length} source/config files; ${inventory.files.reduce((count, file) => count + file.symbols.length, 0)} declarations; ${inventory.accessPoints.length} access points; ${records.length} workflow explanation records.`,
    `Extraction completeness: **${inventory.coverage.complete ? 'complete' : 'incomplete'}**. Unreviewed symbols, APIs, pages, commands and legacy source remain searchable as discovery-only facts. Zero matches do not prove absence.`, '',
    `Workflow domains: ${[...domains].slice(0, 16).map(([domain, count]) => `${domain} (${count})`).join(', ')}${domains.size > 16 ? '; further domains available through search' : ''}.`, '',
    '| Workflow / fetch ID | Purpose | Primary source | Lifecycle / evidence / freshness |',
    '| --- | --- | --- | --- |',
  ];
  let shown = 0;
  for (const record of records) {
    const reference = record.entryPoints[0];
    const file = inventory.files.find(file => file.path === reference?.split('#')[0]);
    const symbol = file?.symbols.find(symbol => symbol.id === reference);
    const point = inventory.accessPoints.find(point => point.id === reference);
    const sourcePath = file?.path ?? point?.path;
    const line = symbol?.line ?? point?.line ?? 1;
    const label = symbol?.name ?? sourcePath?.split('/').pop() ?? 'unresolved';
    const source = sourcePath ? `[${cell(label, 38)}](<../../${sourcePath.split('/').map(encodeURIComponent).join('/')}#L${line}>)` : 'Unresolved; inspect record';
    const row = `| ${cell(record.name, 55)}<br>\`${record.id}\` | ${cell(record.purpose, 100)} | ${source} | ${record.lifecycle} / ${record.evidence} / ${catalog.freshness.get(record.id)?.freshness ?? 'unknown'} |`;
    if (shown >= 24 || lines.join('\n').length + row.length > 11000) break;
    lines.push(row); shown++;
  }
  lines.push('', `${shown} of ${records.length} workflow records shown. Use bounded search/get for remaining records, all discovery-only entries, settings, contracts, related APIs/pages/commands and source/dependency evidence.`, '',
    `Snapshot: \`${fingerprint(JSON.stringify([inventory.snapshotFingerprint, inventory.extractorFingerprint, catalog.records]))}\`.`, '');
  return lines.join('\n');
}
